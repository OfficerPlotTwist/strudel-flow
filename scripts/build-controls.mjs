/**
 * Renders the controls sheet to docs/controls.html.
 *
 * Generated rather than written, so it cannot drift from the bindings - the
 * data lives in src/controls-doc.js and tests/controls-doc.test.js checks that
 * data against main.js. Editing this page by hand would be editing the wrong
 * file, which is why it says so at the top of the output.
 *
 *   node scripts/build-controls.mjs [--open]
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
import { KEYBOARD, SURFACE } from '../src/controls-doc.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../docs/controls.html');

const escape = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const keyRow = ([key, does]) => `
      <tr><th>${escape(key)}</th><td>${escape(does)}</td></tr>`;

const surfaceRow = ([, label, does, mode]) => `
      <tr>
        <th>${escape(label)}</th>
        <td>${escape(does)}</td>
        <td class="mode">${mode ? escape(mode) : ''}</td>
      </tr>`;

const section = (title, head, rows) => `
  <section>
    <h2>${escape(title)}</h2>
    <table>
      <thead><tr>${head}</tr></thead>
      <tbody>${rows}</tbody>
    </table>
  </section>`;

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Strudel stack — controls</title>
<style>
  :root {
    --bg: #0b120d; --bg-raised: #121c15; --phosphor: #5ef08a;
    --phosphor-dim: #3a7d55; --rule: #1d3226;
  }
  * { box-sizing: border-box; }
  body {
    margin: 0; padding: 2rem 1.5rem 4rem;
    background: var(--bg); color: var(--phosphor);
    font-family: "Consolas", "DejaVu Sans Mono", monospace;
    font-size: 14px; line-height: 1.5;
  }
  main { max-width: 62rem; margin: 0 auto; }
  h1 { font-size: 1.4rem; margin: 0 0 .25rem; letter-spacing: .04em; }
  .sub { color: var(--phosphor-dim); margin: 0 0 2rem; font-size: .8rem; }
  .cols { column-width: 27rem; column-gap: 2.5rem; }
  section { break-inside: avoid; margin: 0 0 1.75rem; }
  h2 {
    font-size: .78rem; text-transform: uppercase; letter-spacing: .14em;
    color: var(--phosphor-dim); margin: 0 0 .5rem;
    border-bottom: 1px solid var(--rule); padding-bottom: .3rem;
  }
  table { width: 100%; border-collapse: collapse; }
  th, td { text-align: left; vertical-align: top; padding: .28rem .5rem .28rem 0; }
  thead th {
    font-size: .65rem; text-transform: uppercase; letter-spacing: .1em;
    color: var(--phosphor-dim); font-weight: normal; padding-bottom: .4rem;
  }
  tbody th { white-space: nowrap; width: 1%; padding-right: 1.1rem; font-weight: normal; }
  tbody tr:nth-child(odd) { background: var(--bg-raised); }
  tbody td { color: #cfe9d8; }
  .mode { color: var(--phosphor-dim); font-size: .78rem; white-space: nowrap; }
  footer {
    margin-top: 2.5rem; padding-top: .75rem; border-top: 1px solid var(--rule);
    color: var(--phosphor-dim); font-size: .72rem;
  }
  @media print { body { background: #fff; color: #000; } tbody tr:nth-child(odd) { background: #f2f2f2; } }
</style>
</head>
<body>
<main>
  <h1>Strudel stack — controls</h1>
  <p class="sub">
    Generated from src/controls-doc.js. Do not edit this file by hand.
    The <em>when</em> column is what has to be true for a row to apply — this
    surface re-scopes controls rather than adding them.
  </p>

  <div class="cols">
${KEYBOARD.map((g) =>
  section(`Keyboard — ${g.group}`, '<th>Key</th><th>Does</th>', g.rows.map(keyRow).join('')),
).join('')}
${SURFACE.map((g) =>
  section(`APC40 — ${g.group}`, '<th>Control</th><th>Does</th><th>When</th>',
    g.rows.map(surfaceRow).join('')),
).join('')}
  </div>

  <footer>
    Built ${new Date().toISOString().slice(0, 10)} ·
    every control is checked against main.js by tests/controls-doc.test.js
  </footer>
</main>
</body>
</html>
`;

await mkdir(dirname(out), { recursive: true });
await writeFile(out, page, 'utf8');
console.log(`wrote ${out}`);

if (process.argv.includes('--open')) {
  // start "" "<file>" is the Windows shell's own opener; xdg-open/open elsewhere.
  const [cmd, args] =
    process.platform === 'win32'
      ? ['cmd', ['/c', 'start', '', out]]
      : [process.platform === 'darwin' ? 'open' : 'xdg-open', [out]];
  spawn(cmd, args, { detached: true, stdio: 'ignore' }).unref();
  console.log('opened in your browser');
}
